#!/usr/bin/env python3
"""Export configs/params.json to src/cpp/params.h (Single source of truth).

Generates strongly typed C++17 constexpr constants in namespace `params`.
"""

import argparse
import json
from pathlib import Path
from typing import Any, Dict


def format_cpp_value(val: Any) -> str:
    """Format Python value as C++ literal."""
    if isinstance(val, bool):
        return "true" if val else "false"
    elif isinstance(val, int):
        return str(val)
    elif isinstance(val, float):
        # Format floating point numbers accurately
        s = repr(val)
        if "e" not in s and "." not in s:
            s += ".0"
        return s
    elif isinstance(val, str):
        return f'"{val}"'
    else:
        raise TypeError(f"Unsupported parameter type: {type(val)}")


def get_cpp_type(val: Any) -> str:
    """Get C++ type string for parameter value."""
    if isinstance(val, bool):
        return "bool"
    elif isinstance(val, int):
        return "int64_t"
    elif isinstance(val, float):
        return "double"
    elif isinstance(val, str):
        return "const char*"
    else:
        raise TypeError(f"Unsupported parameter type: {type(val)}")


def generate_params_header(params: Dict[str, Any]) -> str:
    """Generate C++ header content from parameters dictionary."""
    lines = [
        "// Auto-generated by tools/export_params.py from configs/params.json",
        "// DO NOT EDIT DIRECTLY.",
        "#ifndef PARAMS_H",
        "#define PARAMS_H",
        "",
        "#include <cstdint>",
        "",
        "namespace params {",
        "",
    ]

    for key, val in params.items():
        cpp_type = get_cpp_type(val)
        cpp_val = format_cpp_value(val)
        lines.append(f"constexpr {cpp_type} {key} = {cpp_val};")

    lines.extend([
        "",
        "} // namespace params",
        "",
        "#endif // PARAMS_H",
        "",
    ])

    return "\n".join(lines)


def export_params(json_path: Path, header_path: Path) -> None:
    """Read json_path and write header_path."""
    with open(json_path, "r", encoding="utf-8") as f:
        params = json.load(f)

    content = generate_params_header(params)

    header_path.parent.mkdir(parents=True, exist_ok=True)
    with open(header_path, "w", encoding="utf-8") as f:
        f.write(content)


def main() -> None:
    repo_root = Path(__file__).resolve().parent.parent
    default_json = repo_root / "configs" / "params.json"
    default_header = repo_root / "src" / "cpp" / "params.h"

    parser = argparse.ArgumentParser(description="Export params.json to C++ params.h")
    parser.add_argument(
        "--input",
        type=Path,
        default=default_json,
        help=f"Input JSON path (default: {default_json})",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=default_header,
        help=f"Output C++ header path (default: {default_header})",
    )
    args = parser.parse_args()

    export_params(args.input, args.output)
    print(f"Exported {args.input} -> {args.output}")


if __name__ == "__main__":
    main()
